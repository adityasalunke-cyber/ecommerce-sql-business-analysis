-- E-commerce SQL practice dataset (MySQL 8 compatible)
-- Tables: customers (150), products (130), orders (500)


DROP DATABASE IF EXISTS ecommerce_practice;
CREATE DATABASE ecommerce_practice;
USE ecommerce_practice;

CREATE TABLE customers (
  customer_id INT PRIMARY KEY,
  first_name VARCHAR(50) NOT NULL,
  last_name VARCHAR(50) NOT NULL,
  email VARCHAR(100) UNIQUE NOT NULL,
  phone VARCHAR(15),
  gender ENUM('Male','Female','Other'),
  date_of_birth DATE,
  city VARCHAR(50),
  state VARCHAR(50),
  signup_date DATE NOT NULL,
  loyalty_tier ENUM('Bronze','Silver','Gold','Platinum') DEFAULT 'Bronze',
  is_active BOOLEAN DEFAULT TRUE
);

CREATE TABLE products (
  product_id INT PRIMARY KEY,
  product_name VARCHAR(120) NOT NULL,
  category VARCHAR(50) NOT NULL,
  brand VARCHAR(50),
  price DECIMAL(10,2) NOT NULL,
  cost_price DECIMAL(10,2) NOT NULL,
  stock_quantity INT NOT NULL,
  rating DECIMAL(2,1),
  review_count INT DEFAULT 0,
  launch_date DATE,
  is_available BOOLEAN DEFAULT TRUE
);

CREATE TABLE orders (
  order_id INT PRIMARY KEY,
  customer_id INT NOT NULL,
  product_id INT NOT NULL,
  quantity INT NOT NULL,
  unit_price DECIMAL(10,2) NOT NULL,
  discount_percent DECIMAL(4,1) DEFAULT 0,
  total_amount DECIMAL(12,2) NOT NULL,
  order_date DATE NOT NULL,
  order_status ENUM('Placed','Shipped','Delivered','Cancelled','Returned') NOT NULL,
  payment_method ENUM('UPI','Credit Card','Debit Card','Net Banking','Cash on Delivery','Wallet') NOT NULL,
  shipping_city VARCHAR(50),
  delivery_date DATE,
  FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
  FOREIGN KEY (product_id) REFERENCES products(product_id)
);

